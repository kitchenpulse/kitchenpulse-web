export const EQUIPMENT_BY_SLUG: Record<string, EquipmentPageData> = Object.fromEntries(
  EQUIPMENT_PAGES.map((p) => [p.slug, p]),
);

export function getEquipmentPage(slug: string): EquipmentPageData | undefined {
  return EQUIPMENT_BY_SLUG[slug];
}

export function getEquipmentHub(): EquipmentPageData {
  return EQUIPMENT_BY_SLUG[""];
}

export function listEquipmentSlugs(): string[] {
  return EQUIPMENT_PAGES.filter((p) => p.slug !== "").map((p) => p.slug);
}

export function getRelatedPages(slugs: string[]): EquipmentPageData[] {
  return slugs
    .map((s) => EQUIPMENT_BY_SLUG[s])
    .filter((p): p is EquipmentPageData => Boolean(p));
}

export function getClusterLeaves(clusterSlug: string): EquipmentPageData[] {
  return EQUIPMENT_PAGES.filter(
    (p) => p.kind === "leaf" && p.clusterSlug === clusterSlug,
  );
}

export const EQUIPMENT_PATHS = EQUIPMENT_PAGES.map((p) =>
  p.slug === "" ? "/equipment" : `/equipment/${p.slug}`,
);

